def criteria_block(codes: list[str]) -> str:
    """Текстовый блок с определениями для промпта."""
    return "\n".join(
        f"- {c} — {CRITERIA[c].name} ({CRITERIA[c].source}): {CRITERIA[c].definition}" for c in codes
    )


def criterion_name(code: str) -> str:
    c = CRITERIA.get(code)
    return c.name if c else code


def is_set_level(code: str) -> bool:
    c = CRITERIA.get(code)
    return bool(c and c.level == "set")
